/**
 * סעיף 36 - התואר שסימון "תלמידנו" בחר כשהתואר היה ריק.
 *
 * ההתנהגות הזו בוטלה בזום עם ישראל ב-03.11: הסימון אינו נוגע בשדה התואר
 * כלל. הקבוע נשאר כי הוא עדיין הערך שיושב אצל תורמים שסומנו לפני השינוי,
 * וההמרה שלהם מזהה אותם לפיו.
 */
export const ALUMNI_TITLE = 'תלמידנו הרה"ח ר\''

/**
 * סעיף 36 - הקידומת שמתווספת בהפקת המכתב כשהתורם מסומן "תלמידנו".
 *
 * ישראל, 03.11: "כשאני מגדיר תלמידנו, הוא לא נוגע בכלל בשורת התואר, הוא
 * מתווסף לפני שורת התואר". כלומר "תלמידנו הרב הגאון", "תלמידנו הגאון החסיד"
 * - התואר שהמשתמש בחר נשאר כפי שהוא, והקידומת מולבשת עליו בזמן ההפקה בלבד.
 */
export const ALUMNI_LETTER_PREFIX = 'תלמידנו'

/**
 * התואר כפי שהוא נכתב במכתב.
 *
 * כאן ולא בקומפוננטה: אותו כלל יידרש בכל מקום שמפיק מכתב או מעטפה, וכפילות
 * שלו היא בדיוק מה שיצר את הפער בין מה שהמסך הראה למה שיצא בדפוס.
 *
 * הקידומת אינה מוכפלת: תואר שכבר פותח ב"תלמידנו" (למשל ALUMNI_TITLE, שנקבע
 * אצל תורמים שסומנו לפני 03.11) מוחזר כפי שהוא.
 */
export function titleForLetter(title: string | null | undefined, isAlumni: boolean): string {
  const value = (title || '').trim()
  if (!isAlumni) return value
  if (value.startsWith(ALUMNI_LETTER_PREFIX)) return value
  return value ? `${ALUMNI_LETTER_PREFIX} ${value}` : ALUMNI_LETTER_PREFIX
}

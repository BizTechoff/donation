/** מחרוזת כליטרל SQL: 'O''Brien'. */
export function lit(value: string | null | undefined): string {
  return `'${String(value ?? '').replace(/'/g, "''")}'`
}

/** כותרת אחידה לקובץ SQL שכלי הפיק. */
export function sqlHeader(title: string): string {
  return [
    '-- =================================================================',
    `-- ${title}`,
    '-- מודפס בלבד, לא הורץ.',
    '-- ================================================================='
  ].join('\n')
}
